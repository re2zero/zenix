//! Hook template installation — writes herdr integration hooks
//! to agent CLI hook directories.
//!
//! Each hook template contains a `HERDR_INTEGRATION_VERSION=N` line
//! used by `agent::detect_all_agents()` for version detection.
//! Templates are embedded at compile time as const strings.

use std::path::PathBuf;

use crate::provider::ProviderRegistry;

// ── Hook templates ───────────────────────────────────────────────────

/// Shell hook template (Claude, Codex, Copilot, Droid, Kimi, Qoder, Cursor).
const HOOK_SH: &str = r#"#!/usr/bin/env bash
# herdr agent-state hook — shell variant
# Generated by zenix

HERDR_INTEGRATION_VERSION=5

herdr_agent_state() {
    local event="$1"
    local payload="$2"

    case "$event" in
        pre_prompt)
            # Notify herdr of agent state change
            if command -v herdr &>/dev/null; then
                herdr agent notify --event "$event" --payload "$payload" 2>/dev/null || true
            fi
            ;;
        *)
            ;;
    esac
}

# Called by the agent CLI before each prompt
herdr_agent_state "$@"
"#;

/// JavaScript hook template (OpenCode, Kilo).
const HOOK_JS: &str = r#"// herdr agent-state hook — JavaScript variant
// Generated by zenix
// HERDR_INTEGRATION_VERSION=5

const { execSync } = require('child_process');

function herdrAgentState(event, payload) {
    if (event === 'pre_prompt') {
        try {
            const herdr = 'herdr';
            execSync(`${herdr} agent notify --event ${event} --payload '${JSON.stringify(payload)}'`, {
                stdio: 'ignore',
                timeout: 2000
            });
        } catch (e) {
            // herdr not available — non-fatal
        }
    }
}

module.exports = { herdrAgentState };
"#;

/// TypeScript hook template (Pi, OMP).
const HOOK_TS: &str = r#"// herdr agent-state hook — TypeScript variant
// Generated by zenix
// HERDR_INTEGRATION_VERSION=5

import { execSync } from 'child_process';

export function herdrAgentState(event: string, payload: any): void {
    if (event === 'pre_prompt') {
        try {
            const herdr = 'herdr';
            execSync(`${herdr} agent notify --event ${event} --payload '${JSON.stringify(payload)}'`, {
                stdio: 'ignore',
                timeout: 2000
            });
        } catch (e) {
            // herdr not available — non-fatal
        }
    }
}
"#;

/// Python hook template (Hermes).
const HOOK_PY: &str = r#"# herdr agent-state hook — Python variant
# Generated by zenix

HERDR_INTEGRATION_VERSION = 5

import subprocess
import json


def herdr_agent_state(event: str, payload: dict = None) -> None:
    if event == "pre_prompt":
        try:
            subprocess.run(
                ["herdr", "agent", "notify", "--event", event,
                 "--payload", json.dumps(payload or {})],
                timeout=2,
                capture_output=True,
            )
        except Exception:
            pass  # herdr not available — non-fatal
"#;

// ── Template resolver ─────────────────────────────────────────────────

/// Return the hook template content for a given file extension.
fn template_for_ext(ext: &str) -> Option<&'static str> {
    match ext {
        "sh" => Some(HOOK_SH),
        "js" => Some(HOOK_JS),
        "ts" => Some(HOOK_TS),
        "py" => Some(HOOK_PY),
        _ => None,
    }
}

/// Extract file extension from a hook filename.
fn ext_from_filename(filename: &str) -> Option<&'static str> {
    if filename.ends_with(".sh") {
        Some("sh")
    } else if filename.ends_with(".js") {
        Some("js")
    } else if filename.ends_with(".ts") {
        Some("ts")
    } else if filename.ends_with(".py") {
        Some("py")
    } else {
        None
    }
}

// ── Public API ────────────────────────────────────────────────────────

/// Install (or update) the herdr integration hook for a named agent.
///
/// Looks up the agent in `ProviderRegistry`, resolves the hook directory
/// and filename, creates any missing directories, and writes the template.
/// Returns the hook file path on success.
pub fn install_hook(agent_name: &str) -> Result<PathBuf, String> {
    let registry = ProviderRegistry::builtin();
    let provider = registry.find(agent_name)
        .ok_or_else(|| format!("unknown agent: {agent_name}"))?;

    let hook_dir = provider.hook_dir_path()
        .ok_or_else(|| format!("agent '{agent_name}' does not support hooks"))?;
    let filename = provider.hook_filename
        .ok_or_else(|| format!("agent '{agent_name}' has no hook filename"))?;

    let ext = ext_from_filename(filename)
        .ok_or_else(|| format!("unsupported hook extension for '{filename}'"))?;
    let template = template_for_ext(ext)
        .ok_or_else(|| format!("no template for extension '{ext}'"))?;

    // Create hook directory if it doesn't exist
    std::fs::create_dir_all(&hook_dir)
        .map_err(|e| format!("create hook dir {}: {e}", hook_dir.display()))?;

    let hook_path = hook_dir.join(filename);
    std::fs::write(&hook_path, template)
        .map_err(|e| format!("write hook {}: {e}", hook_path.display()))?;

    tracing::info!("installed hook for {agent_name} at {}", hook_path.display());
    Ok(hook_path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_template_for_ext() {
        assert!(template_for_ext("sh").is_some());
        assert!(template_for_ext("js").is_some());
        assert!(template_for_ext("ts").is_some());
        assert!(template_for_ext("py").is_some());
        assert!(template_for_ext("rb").is_none());
    }

    #[test]
    fn test_ext_from_filename() {
        assert_eq!(ext_from_filename("herdr-agent-state.sh"), Some("sh"));
        assert_eq!(ext_from_filename("herdr-agent-state.js"), Some("js"));
        assert_eq!(ext_from_filename("herdr-agent-state.ts"), Some("ts"));
        assert_eq!(ext_from_filename("__init__.py"), Some("py"));
        assert_eq!(ext_from_filename("unknown.txt"), None);
    }

    #[test]
    fn test_templates_contain_version() {
        assert!(HOOK_SH.contains("HERDR_INTEGRATION_VERSION"));
        assert!(HOOK_JS.contains("HERDR_INTEGRATION_VERSION"));
        assert!(HOOK_TS.contains("HERDR_INTEGRATION_VERSION"));
        assert!(HOOK_PY.contains("HERDR_INTEGRATION_VERSION"));
    }
}